CATEGORY_ID = 1  # Standart Namunalar (GSO)

async def main():
    db = await get_db()
    try:
        added = 0
        updated = 0
        for prod in NEW_GSO_PRODUCTS:
            cursor = await db.execute(
                "SELECT id FROM products WHERE category_id = ? AND code = ?",
                (CATEGORY_ID, prod["code"])
            )
            row = await cursor.fetchone()
            if row:
                await db.execute(
                    """
                    UPDATE products SET 
                        name = ?, standard = ?, accuracy_class = ?, 
                        measurement_range = ?, price = ?, description = ?
                    WHERE id = ?
                    """,
                    (
                        prod["name"], prod["standard"], prod["accuracy_class"],
                        prod["measurement_range"], prod["price"], prod["description"],
                        row["id"]
                    )
                )
                updated += 1
            else:
                await db.execute(
                    """
                    INSERT INTO products (
                        category_id, name, code, standard, accuracy_class,
                        measurement_range, price, description, is_service
                    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, 0)
                    """,
                    (
                        CATEGORY_ID, prod["name"], prod["code"], prod["standard"],
                        prod["accuracy_class"], prod["measurement_range"],
                        prod["price"], prod["description"]
                    )
                )
                added += 1
        await db.commit()
        print(f"Baza muvaffaqiyatli yangilandi: {added} ta yangi qoshildi, {updated} ta yangilandi.")
    finally:
        await db.close()

if __name__ == "__main__":
    asyncio.run(main())
